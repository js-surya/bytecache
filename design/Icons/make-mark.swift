import AppKit
import CoreText

// The ByteCache mark {↓} as a custom SF Symbol, for places that need a symbol rather than text (menu
// bar, tab bar, empty states, widgets): the app icon's bold monospaced braces and its down arrow,
// all as filled outlines (symbols can't have strokes). Scales and takes weight-free tint like any symbol.
// Usage: swift design/Icons/make-mark.swift <path/to/name.symbolset>...

// Drawn in a 22 × 16 box (y up), then placed on Apple's symbol template at 100 pt.
let width = 22.0, height = 16.0
let font = NSFont.monospacedSystemFont(ofSize: 17, weight: .bold) as CTFont

func glyph(_ character: Character) -> CGPath {
    var unichar = Array(String(character).utf16)
    var glyph = CGGlyph()
    CTFontGetGlyphsForCharacters(font, &unichar, &glyph, 1)
    return CTFontCreatePathForGlyph(font, glyph, nil)!
}

func placed(_ path: CGPath, x: Double) -> CGPath {
    let b = path.boundingBoxOfPath
    var t = CGAffineTransform(translationX: x - b.minX, y: (height - b.height) / 2 - b.minY)
    return path.copy(using: &t)!
}

let mark = CGMutablePath()
let right = glyph("}")
mark.addPath(placed(glyph("{"), x: 0.5))
mark.addPath(placed(right, x: width - 0.5 - right.boundingBoxOfPath.width))
let arrow = CGMutablePath()
let cx = width / 2, top = 12.4, bottom = 3.6, head = 3.0
arrow.move(to: CGPoint(x: cx, y: top)); arrow.addLine(to: CGPoint(x: cx, y: bottom))
arrow.move(to: CGPoint(x: cx - head, y: bottom + head)); arrow.addLine(to: CGPoint(x: cx, y: bottom))
arrow.addLine(to: CGPoint(x: cx + head, y: bottom + head))
mark.addPath(arrow.copy(strokingWithWidth: 2.1, lineCap: .round, lineJoin: .round, miterLimit: 10).normalized())

// Template v.3.0 geometry: medium baseline y 1126, cap height 70.459. The mark is centred on the
// cap height and a little taller than capitals, like other tab bar symbols.
let scale = 6.8, middle = 1091.0, left = 1380.0
func svgPath(_ path: CGPath) -> String {
    func p(_ q: CGPoint) -> String {
        String(format: "%.3f %.3f", left + q.x * scale, middle + (height / 2 - q.y) * scale)
    }
    var d = ""
    path.applyWithBlock { element in
        let e = element.pointee
        switch e.type {
        case .moveToPoint: d += "M\(p(e.points[0]))"
        case .addLineToPoint: d += "L\(p(e.points[0]))"
        case .addQuadCurveToPoint: d += "Q\(p(e.points[0])) \(p(e.points[1]))"
        case .addCurveToPoint: d += "C\(p(e.points[0])) \(p(e.points[1])) \(p(e.points[2]))"
        case .closeSubpath: d += "Z"
        @unknown default: break
        }
    }
    return d
}
let marginLeft = left, marginRight = left + width * scale
let line = "style=\"fill:none;stroke:#27AAE1;opacity:1;stroke-width:0.5;\""

let svg = """
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE svg PUBLIC "-//W3C//DTD SVG 1.1//EN" "http://www.w3.org/Graphics/SVG/1.1/DTD/svg11.dtd">
<svg version="1.1" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="3300" height="2200">
 <!--Generated by design/Icons/make-mark.swift-->
 <g id="Notes">
  <text style="stroke:none;fill:black;font-family:sans-serif;font-size:13;" transform="matrix(1 0 0 1 263 1933)">Template v.3.0</text>
 </g>
 <g id="Guides">
  <line id="Baseline-S" \(line) x1="263" x2="3036" y1="696" y2="696"/>
  <line id="Capline-S" \(line) x1="263" x2="3036" y1="625.541" y2="625.541"/>
  <line id="Baseline-M" \(line) x1="263" x2="3036" y1="1126" y2="1126"/>
  <line id="Capline-M" \(line) x1="263" x2="3036" y1="1055.54" y2="1055.54"/>
  <line id="Baseline-L" \(line) x1="263" x2="3036" y1="1556" y2="1556"/>
  <line id="Capline-L" \(line) x1="263" x2="3036" y1="1485.54" y2="1485.54"/>
  <line id="left-margin-Regular-M" \(line) x1="\(marginLeft)" x2="\(marginLeft)" y1="1030.79" y2="1150.12"/>
  <line id="right-margin-Regular-M" \(line) x1="\(marginRight)" x2="\(marginRight)" y1="1030.79" y2="1150.12"/>
 </g>
 <g id="Symbols">
  <g id="Regular-M">
   <path d="\(svgPath(mark))"/>
  </g>
 </g>
</svg>

"""
for folder in CommandLine.arguments.dropFirst() {
    let url = URL(filePath: folder)
    let name = url.deletingPathExtension().lastPathComponent
    try FileManager.default.createDirectory(at: url, withIntermediateDirectories: true)
    try svg.write(to: url.appending(path: "\(name).svg"), atomically: true, encoding: .utf8)
    try """
    {
      "info" : { "author" : "xcode", "version" : 1 },
      "symbols" : [ { "filename" : "\(name).svg", "idiom" : "universal" } ]
    }

    """.write(to: url.appending(path: "Contents.json"), atomically: true, encoding: .utf8)
}
